path = next((a for a in sys.argv[1:] if not a.startswith("--")), "/data/database.sqlite")
apply = "--apply" in sys.argv
db = sqlite3.connect(path, timeout=30)
todo = {}
for kind, ids in PRIVATE.items():
    for record_id in ids:
        row = db.execute("SELECT COALESCE(is_public, 0) FROM library_items WHERE kind = ? AND id = ?", (kind, record_id)).fetchone()
        if row and row[0]:
            todo.setdefault(kind, []).append(record_id)
print(path)
print("Currently public but private in DEV:", {kind: len(ids) for kind, ids in todo.items()}, "total", sum(len(v) for v in todo.values()))
if not apply:
    print("Dry run: nothing changed. Add --apply to make them private.")
    sys.exit(0)
backup = os.path.join(os.path.dirname(os.path.abspath(path)), "database.pre-private.sqlite")
with sqlite3.connect(backup) as target:
    db.backup(target)
print("Backup written to", backup)
db.executemany("UPDATE library_items SET is_public = 0 WHERE kind = ? AND id = ?", [(k, i) for k, ids in todo.items() for i in ids])
db.commit()
print("Done.")
